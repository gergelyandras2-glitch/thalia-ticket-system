package hu.szinhaz.ticket;

import hu.szinhaz.ticket.dto.PerformanceCreateDto;
import hu.szinhaz.ticket.model.Performance;
import hu.szinhaz.ticket.model.TheaterHall;
import hu.szinhaz.ticket.repository.TheaterHallRepository;
import hu.szinhaz.ticket.service.PerformanceService;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
public class PerformanceServiceTest {

    @Autowired
    private PerformanceService performanceService;

    @Autowired
    private TheaterHallRepository hallRepository;

    @Test
    @Transactional
    @DisplayName("FR-01: Előadások keresése címre és műfaji szűrés")
    void testSearchAndFilter() {
        List<Performance> all = performanceService.findAll();
        assertFalse(all.isEmpty());

        // Keresés címrészletre
        List<Performance> matches = performanceService.search("szonáta", null, null);
        assertFalse(matches.isEmpty());
        assertTrue(matches.get(0).getTitle().toLowerCase().contains("szonáta"));

        // Keresés műfajra
        List<Performance> musicals = performanceService.search(null, "Musical", null);
        assertFalse(musicals.isEmpty());
        assertEquals("Musical", musicals.get(0).getGenre());
    }

    @Test
    @Transactional
    @DisplayName("FR-07: Új előadás létrehozása és terem szerinti ülésgenerálás")
    void testCreatePerformanceWithAutoGeneratedSeats() {
        TheaterHall hall = hallRepository.findAll().get(0);
        int expectedSeats = hall.getRowsCount() * hall.getColsCount();

        PerformanceCreateDto dto = new PerformanceCreateDto();
        dto.setTitle("Új Próbaelőadás");
        dto.setAuthor("Kortárs Szerző");
        dto.setDescription("Színházi premier előadás leírása");
        dto.setGenre("Kortárs");
        dto.setDateTime(LocalDateTime.now().plusDays(15));
        dto.setBasePrice(BigDecimal.valueOf(4200));
        dto.setDurationMinutes(110);
        dto.setHallId(hall.getId());

        Performance created = performanceService.createPerformance(dto);

        assertNotNull(created.getId());
        assertEquals(expectedSeats, created.getSeats().size());
        assertEquals(expectedSeats, created.getAvailableSeatsCount());
    }
}
